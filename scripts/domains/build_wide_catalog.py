def D(name, description, choice, noul, score, **attributes):
    """attributes pin prompt attributes (region, industry, ...) where the domain only makes sense in one."""
    choice_instructions, options = choice
    noul_instructions, when_false, when_true = noul
    scored, levels = score
    level_names = ", ".join(f"{i} {level}" for i, (level, _) in enumerate(levels))
    entry = {
        "description": description,
        "questions": {
            "action": {"type": "choice", "instructions": choice_instructions, "criteria": dict(options)},
            "check": {"type": "noul", "instructions": noul_instructions,
                      "criteria": {"false": when_false, "true": when_true}},
            "level": {"type": "score", "instructions": f"{scored} Levels: {level_names}.",
                      "criteria": [f"{level.capitalize()}: {meaning}" for level, meaning in levels]},
        },
    }
    if attributes:
        entry["attributes"] = attributes
    return name, entry


