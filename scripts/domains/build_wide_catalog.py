"""Build scripts/domains/catalog_wide.json: 220 decision domains, 10 in each of 22 areas.

Research on general classifiers (Hsieh et al. 2023; the zeroshot-v2.0 models trained on hundreds of
synthetic tasks) finds that many different tasks with fewer rows each generalise better than a few
tasks with many rows. This catalog is that breadth. Every domain has three questions, one of each
type: a choice (what to do), a noul (a yes/no check) and a score (an ordinal level).

Each domain is one line, D(name, description, choice, noul, score):
- choice: (instructions, {option_id: meaning, ...}) with 3 to 5 options
- noul: (instructions, meaning when false, meaning when true)
- score: (what is scored, [(level name, meaning) x 4])

The names never repeat catalog.json or benchmark.json (tests/test_wide_catalog.py checks it).
Rebuild after editing: python scripts/domains/build_wide_catalog.py
"""
