def build(path: Path = OUTPUT) -> Path:
    domains = dict(DOMAINS)
    if len(domains) != len(DOMAINS):
        raise ValueError("a domain name repeats")
    catalog = {"version": VERSION, "domains": domains}
    path.write_text(json.dumps(catalog, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return path


